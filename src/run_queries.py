"""Run every query in sql/analysis_queries.sql and write sql/results.md."""
import re
import sqlite3

import pandas as pd

from config import DB_PATH, SQL_DIR

MAX_ROWS = 50


def main() -> None:
    text = (SQL_DIR / "analysis_queries.sql").read_text()
    parts = re.split(r"^-- (Q\d+: .*)$", text, flags=re.M)
    out = ["# Query results", "", "Generated by `python src/run_queries.py` from `data/ca_jobs.db`.", ""]
    with sqlite3.connect(DB_PATH) as conn:
        for title, sql in zip(parts[1::2], parts[2::2]):
            df = pd.read_sql_query(sql, conn)
            out += [f"## {title}", "", df.head(MAX_ROWS).to_markdown(index=False), ""]
            print(f"{title} -> {len(df)} rows")
    (SQL_DIR / "results.md").write_text("\n".join(out))
    print(f"wrote {SQL_DIR / 'results.md'}")


if __name__ == "__main__":
    main()
